"""Validate the embedded catalog and generate localized installer text and offline guides.

Run before packaging. English keys are canonical; templates use numbered slots.
No network access or external translation service is used.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGUAGES = ("en", "de", "es", "pt", "fr", "it")


def generate():
    version = re.search(r'^version = "([^"]+)"', (ROOT / "Cargo.toml").read_text(), re.M)[1]
    catalog = json.loads((ROOT / "locales/catalog.json").read_text(encoding="utf-8"))
    custom = json.loads((ROOT / "installer/translations.json").read_text(encoding="utf-8"))
    custom["Preview"] = [re.sub(r"\s+\d+\.\d+\.\d+$", "", text) + " " + version for text in custom["Preview"]]
    for key, values in catalog.items():
        assert len(values) == 6 and key == values[0], key
        placeholders = sorted(re.findall(r"\{\d+\}", key))
        for value in values:
            assert value and placeholders == sorted(re.findall(r"\{\d+\}", value)), key
    for values in custom.values():
        assert len(values) == 6 and all(values)
    for path in (ROOT / "src").rglob("*.rs"):
        for key in re.findall(r'(?:\btr|i18n::format)\(\s*("(?:\\.|[^"\\])*")', path.read_text(encoding="utf-8")):
            assert json.loads(key) in catalog, (path, key)
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    messages = ["; Generated by scripts/locales.py. Edit the JSON catalogs.", "[Messages]"]
    customs = ["[CustomMessages]"]
    keys = list(catalog)
    def find(prefix):
        matches = [k for k in keys if k.startswith(prefix)]
        assert len(matches) == 1, (prefix, matches)
        return matches[0]
    guide_prefixes = ["Get started in four steps", "1. MariaDB", "2. Add and test", "3. Create a plan:", "4. Start the agent.", "What we verify", "We check the tool exit", "Consistency and scheduling", "MySQL/MariaDB use", "When the agent returns", "New plans use UTC.", "Local data and uninstall", "Settings are in %LOCALAPPDATA%", "Choose your language."]
    for i, code in enumerate(LANGUAGES):
        def t(prefix):
            return catalog[find(prefix)][i]
        def msg(key, value):
            assert "\r" not in value
            messages.append(f"{code}.{key}=" + value.replace("\n", "%n"))
        msg("WelcomeLabel1", t("YOUR DATA."))
        msg("WelcomeLabel2", t("MariaDB, MySQL and PostgreSQL.") + "\n\n" + t("1. MariaDB")[3:] + "\n\n" + t("Existing backups and databases"))
        msg("FinishedHeadingLabel", custom["Ready"][i])
        msg("FinishedLabel", t("Add your first connection") + "\n\n" + t("Your credentials stay") + "\n\n" + t("Existing backups and databases"))
        for key, values in custom.items():
            customs.append(f"{code}.{key}={values[i]}")
        customs.append(f"{code}.OpenApp={t('Open StrajaBackupSQL')}")
        title = "StrajaBackupSQL — " + custom["Preview"][i]
        info = title + "\n\n" + t("1. MariaDB")[3:] + "\n\n" + t("The agent runs independently") + "\n\n" + t("We check the tool exit") + "\n\n" + t("Settings are in %LOCALAPPDATA%")
        # BOM makes Inno's plain-text wizard pages unambiguously Unicode.
        (ROOT / f"installer/prerequisites.{code}.txt").write_text(info + "\n", encoding="utf-8-sig")
        (ROOT / f"installer/language.{code}.txt").write_text(code + "\n", encoding="ascii")
        (docs / f"Guide.{code}.txt").write_text(title + "\nstrajabackup.com\n\n" + "\n\n".join(t(p) for p in guide_prefixes) + "\n", encoding="utf-8-sig")
    (ROOT / "installer/localized-messages.iss").write_text("\n".join(messages + customs) + "\n", encoding="utf-8")
    print(f"Validated {len(catalog)} messages in all six languages; generated installer text and offline guides.")


if __name__ == "__main__":
    generate()
